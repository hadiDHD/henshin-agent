import fs from 'fs';
import path from 'path';

export function renderMarkdown(evaluation) {
  let intentContent = "Intent files not found.";
  if (fs.existsSync(evaluation.intent.resolvedPath)) {
    intentContent = fs.readFileSync(evaluation.intent.resolvedPath, 'utf8');
  } else if (fs.existsSync(evaluation.intent.initialPath)) {
    intentContent = fs.readFileSync(evaluation.intent.initialPath, 'utf8');
  }

  const t1Status = evaluation.validation.tier1.ok ? "✅ Pass" : "❌ Fail";
  const t2Status = evaluation.validation.tier2.ok ? "✅ Pass" : "❌ Fail";
  const t3Count = evaluation.validation.tier3.length;
  const t3Passed = evaluation.validation.tier3.filter(r => r.applied).length;

  let examplesTable = "| Role | Purpose | Before | After | Applied |\n| :--- | :--- | :--- | :--- | :--- |\n";
  for (const ex of evaluation.examplesPresented) {
    examplesTable += `| ${ex.role} | ${ex.purpose} | \`${ex.before}\` | \`${ex.after}\` | ✅ |\n`;
  }

  // Also include examples that didn't apply if any
  for (const t3 of evaluation.validation.tier3) {
    if (!t3.applied) {
      examplesTable += `| ${t3.role} | - | \`${t3.model}\` | - | ❌ (${t3.reason || 'N/A'}) |\n`;
    }
  }

  return `# Evaluation: ${evaluation.rule.name} (v${evaluation.rule.version})

## Summary
${evaluation.agentSummary}

## Rule Information
- **Path**: \`${evaluation.rule.path}\`
- **Metamodel**: \`${evaluation.metamodel}\`
- **Created At**: ${evaluation.createdAt}

## Intent
> ${intentContent.trim()}

## Validation Results
- **Tier 1 (Structural)**: ${t1Status}
- **Tier 2 (Semantic)**: ${t2Status}
- **Tier 3 (Application)**: ${t3Passed}/${t3Count} applied

## Examples
${examplesTable}

## Decision
Please evaluate the rule and examples above. You can record your decision using the following commands:

- **Accept**:
  \`\`\`bash
  node tools/evaluation/cli.mjs decide --session ${evaluation.sessionId} --verdict accept
  \`\`\`
- **Reject**:
  \`\`\`bash
  node tools/evaluation/cli.mjs decide --session ${evaluation.sessionId} --verdict reject --fault "Description of the issue"
  \`\`\`

---
*Generated by Henshin Evaluation Tool (Phase 3 Payload)*
`;
}
